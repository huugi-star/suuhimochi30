export function pickMemoryCallout(kind: MemoryCalloutKind, random: () => number) {
  const pool = CALLOUTS[kind];
  return pool[Math.min(pool.length - 1, Math.floor(random() * pool.length))] ?? pool[0] ?? 'ちょっと聞いてほしいの。';
}

function c(id: string, label: string, reaction: MemoryReaction, meaning: string, reply: string | string[], afterthought: string): MemoryConversationChoice {
  return { id, label, reaction, meaning, reply: Array.isArray(reply) ? reply : [reply], afterthought };
}

function word(context: MemoryConversationBuildContext, side: 'A' | 'B' = 'A') {
  return side === 'A' ? context.wordA.surface : context.wordB?.surface ?? context.wordA.surface;
}

function label(context: MemoryConversationBuildContext, index = 0) {
  return context.evidence[index]?.label ?? 'まだ詳しく教わっていないところ';
}

type Focus = 'ideas' | 'story' | 'world' | 'words' | 'visual' | 'voice' | 'melody' | 'person' | 'challenge' | 'explore' | 'repeat' | 'history' | 'life' | 'method' | 'generic';

// These labels change wording only. The engine still owns eligibility and
// axis/value matching; this function never adds evidence or changes memory.
function focus(x: MemoryConversationBuildContext, index = 0): Focus {
  const value = label(x, index);
  // Negative or comparative claims need their original wording; matching a
  // noun inside them must not turn them into a positive preference.
  if (/ない|苦手|嫌い|より/.test(value)) return 'generic';
  if (/読み返|見返|繰り返|リピート|何度も聴|何回も聴/.test(value)) return 'repeat';
  if (/歌詞|文章|言葉づかい|言葉遣い|言い方|言葉そのもの/.test(value)) return 'words';
  if (/考え方|知識|思想|哲学|見方/.test(value)) return 'ideas';
  if (/世界観|世界.*魅力|世界.*好き|世界を|舞台設定/.test(value)) return 'world';
  if (/物語|展開|ストーリー/.test(value)) return 'story';
  if (/声|歌声/.test(value)) return 'voice';
  if (/メロディ|旋律|リズム/.test(value)) return 'melody';
  if (/絵|デザイン|見た目|映像|コマ|見せ方/.test(value)) return 'visual';
  if (/難し|挑戦|勝負|上達|攻略|技術|腕前/.test(value)) return 'challenge';
  if (/探索|収集|集め|寄り道/.test(value)) return 'explore';
  if (/キャラクター|性格|人柄|出演者/.test(value)) return 'person';
  if (/歴史|時代|昔の|経緯/.test(value)) return 'history';
  if (/暮らし|生活|生き方|普段/.test(value)) return 'life';
  if (/作り方|手順|仕組み|方法|工夫/.test(value)) return 'method';
  return 'generic';
}

function part(x: MemoryConversationBuildContext, index = 0) {
  const parts: Record<Focus, string> = {
    ideas: '考え方', story: 'お話の流れ', world: 'その世界', words: '言葉', visual: '絵や見た目', voice: '声', melody: 'メロディ', person: 'そこにいる人', challenge: '難しいところに挑むこと', explore: '探したり集めたりすること', repeat: '同じものへ戻ること', history: 'そこまでの歴史', life: '普段の暮らし', method: '作り方や仕組み', generic: `「${label(x, index)}」という話`,
  };
  return parts[focus(x, index)];
}

function recall(x: MemoryConversationBuildContext, index = 0, side: 'A' | 'B' = 'A') {
  if (!x.evidence[index]?.label) return `${word(x, side)}の細かいところは、まだ教わってないの。`;
  const value = label(x, index);
  if (focus(x, index) === 'repeat') return `${word(x, side)}は、一度きりじゃなく、また戻ることがあるって教えてくれたよね。`;
  // Keep the user's exact claim when no safe paraphrase is available. Quoted
  // evidence is a recollection, not a noun to append to arbitrary grammar.
  const conversational = value.replace(/印象に残る/g, '頭に残る').replace(/言葉づかい/g, '言葉の感じ').replace(/読み返している/g, '読み返してる');
  return `${word(x, side)}のこと、${conversational}って話してくれたよね。`;
}

function changingQuestion(x: MemoryConversationBuildContext) {
  switch (focus(x)) {
    case 'ideas': return '前にはうなずいた考えに、別の日は「ちょっと違う」って思うこともある？';
    case 'words': return '同じ言葉なのに、別の日には違うところで立ち止まったりする？';
    case 'story': return '同じお話でも、その日の気分で応援する人や気になる場面が変わる？';
    case 'world': return '同じ世界なのに、行きたい場所がその日で変わったりする？';
    case 'voice': case 'melody': return '同じ音でも、今日は近く感じるとか、今日は遠く感じるとかある？';
    case 'visual': return '同じ絵や形でも、前には見なかったところへ目が行くことある？';
    case 'challenge': return '昨日はもう一回って思えたところも、今日はここまででいいってなる？';
    case 'repeat': return 'また戻った時、同じもののはずなのに前と違って感じることある？';
    default: return '前に教えてくれたところ、今日も同じ感じ？ 別の日には違う受け取り方になる？';
  }
}

function laterImage(x: MemoryConversationBuildContext) {
  switch (focus(x)) {
    case 'ideas': return '同じ考えに会っても、返事するぼくは昨日と違うかもしれないの。';
    case 'words': return '昨日は通り過ぎた一言に、今日は足を止めることもあるのかな。';
    case 'story': return '結末が同じでも、隣に座りたい人は変わるかもしれないの。';
    case 'world': return 'ぼくなら同じ世界に戻って、前には曲がらなかった角を曲がってみたいの。';
    case 'voice': case 'melody': return '音は同じでも、耳の方が違う席に座る感じなのかな。';
    case 'visual': return '絵は動いてないのに、ぼくの目だけ寄り道が増えそうなの。';
    case 'challenge': return 'ぼくなら壁の高さは同じでも、その日の足に相談しちゃうの。';
    case 'repeat': return '同じ入口を通っても、戻ってきた自分まで同じとは限らないのね。';
    default: return 'ぼくなら同じ名前を見つけても、前と同じ顔で会えるか少し迷うの。';
  }
}

function previousLine(x: MemoryConversationBuildContext) {
  return x.previous
    ? `この前、${word(x)}の話で「${x.previous.choiceLabel}」って返事をくれたでしょ。`
    : `${word(x)}のこの話は、まだ前の答えを見つけられてないの。`;
}

function template(family: MemoryConversationFamily, index: number, calloutKinds: readonly MemoryCalloutKind[], build: MemoryConversationTemplate['build']): MemoryConversationTemplate {
  return { id: `memory-${family}-${index + 1}`, family, calloutKinds, build };
}

