function pick<T>(lines: readonly T[], random: () => number) {
  return lines[Math.min(lines.length - 1, Math.floor(random() * lines.length))] ?? lines[0];
}

/** 70% usual, 15% human, 10% remembered word, 5% strange dream. */
export function pickSleepDialogue(word: string | null, random = Math.random) {
  const roll = random();
  if (roll < 0.70) return pick(SLEEP_USUAL_LINES, random);
  if (roll < 0.85) return pick(SLEEP_HUMAN_LINES, random);
  if (roll < 0.95 && word) return pick(SLEEP_WORD_LINES, random).replaceAll('{word}', word);
  if (roll < 0.95) return pick(SLEEP_USUAL_LINES, random);
  return pick(SLEEP_STRANGE_DREAM_LINES, random);
}
