function pickOne<T>(items: readonly T[], random: () => number): T | undefined {
  if (!items.length) return undefined;
  return items[Math.min(items.length - 1, Math.floor(random() * items.length))];
}

function normalizeWord(value: string) {
  return value.normalize('NFKC').trim();
}

function pickLearnedWord(
  words: readonly MonologueLearnedWord[],
  random: () => number,
): MonologueLearnedWord | undefined {
  const valid = words.filter((item) => normalizeWord(item.word));
  if (!valid.length) return undefined;

  const recent = valid.slice(0, Math.min(14, valid.length));
  const pool = random() < 0.72 ? recent : valid;
  return pickOne(pool, random);
}

function buildLearnedWordMonologue(
  words: readonly MonologueLearnedWord[],
  random: () => number,
): string | null {
  const first = pickLearnedWord(words, random);
  if (!first) return null;

  const firstWord = normalizeWord(first.word);

  if (words.length >= 2 && random() < 0.28) {
    const others = words.filter((item) => normalizeWord(item.word) && normalizeWord(item.word) !== firstWord);
    const second = pickLearnedWord(others, random);
    const builder = second ? pickOne(TWO_WORD_LINES, random) : undefined;
    if (second && builder) return builder(firstWord, normalizeWord(second.word));
  }

  const note = first.note?.trim();
  if (note && note.length <= 24 && random() < 0.18) {
    const builder = pickOne(NOTE_LINES, random);
    if (builder) return builder(firstWord, note);
  }

  if (random() < 0.12) {
    const builder = pickOne(MISHEARD_LEARNED_LINES, random);
    if (builder) return builder(firstWord);
  }

  const categoryLines = first.category ? CATEGORY_LEARNED_WORD_LINES[first.category] : undefined;
  const builders = categoryLines?.length
    ? [...categoryLines, ...GENERIC_LEARNED_WORD_LINES]
    : GENERIC_LEARNED_WORD_LINES;
  const builder = pickOne(builders, random);
  return builder?.(firstWord) ?? null;
}

/**
 * 部屋での独り言を1本返す。
 *
 * 学習語がある場合は約66%で学習語を使う。
 * 「説明する」のではなく、覚えた語を生活の中へ勝手に持ち込み、
 * 本人なりの小さな理屈を作る。
 */
export function pickRoomMonologue(
  mochiType: number,
  learnedWords: readonly MonologueLearnedWord[] = [],
  random: () => number = Math.random,
  previousLine = '',
  day?: number,
): string {
  for (let attempt = 0; attempt < 6; attempt += 1) {
    // Each day has its own emotional beat. Keep that beat as the main
    // impression, while still allowing an occasional ordinary observation.
    const dayLines = day === 1 ? DAY_ONE_MONOLOGUES : DAY_SPECIFIC_MONOLOGUES[day ?? 0];
    if (dayLines?.length && random() < 0.84) {
      const choices = dayLines.filter((line) => line !== previousLine);
      const line = pickOne(choices.length ? choices : dayLines, random);
      if (line) return line;
    }

    const learnedLine = learnedWords.length > 0 && random() < 0.66
      ? buildLearnedWordMonologue(learnedWords, random)
      : null;

    const pool = [
      ...(MONOLOGUES[mochiType] ?? MONOLOGUES[1] ?? []),
      ...COMMON_LINES,
    ];
    const choices = pool.filter((line) => line !== previousLine);
    const fallback = pickOne(choices.length ? choices : pool, random)
      ?? '……いま、何か考えてたの。';

    const line = learnedLine ?? fallback;
    if (line !== previousLine) return line;
  }

  return '……さっきと違うこと考えようとしたら、さっきのこと考えてたの。';
}
