import type { CuriousConversation, CuriousConversationBranch, CuriousConversationChoice, CuriousMemoryEffect, DialogueBeat } from '../conversationTypes';

const say = (...texts: string[]): DialogueBeat[] => texts.map((text) => ({ text }));
const choice = (
  id: string,
  label: string,
  lines: string[],
  category: NonNullable<CuriousMemoryEffect['category']>,
  subcategory: string,
  relationQualifier: string,
): CuriousConversationChoice => ({
  id,
  label,
  response: say(...lines),
  memory: { category, subcategory, humanRelations: ['RELATED_TO'], relationQualifier },
});
const branches = (
  id: string,
  knownIntro: string[],
  unknownIntro: string[],
  choices: CuriousConversationChoice[],
) => ({
  known: { response: say(...knownIntro), choices } satisfies CuriousConversationBranch,
  unknown: { response: say(...unknownIntro), choices: choices.map((item) => ({
    ...item,
    id: item.id.replace(`${id}_KNOWN_`, `${id}_UNKNOWN_`),
  })) } satisfies CuriousConversationBranch,
});

